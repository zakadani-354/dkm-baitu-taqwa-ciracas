CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nama VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'pengurus'
        CHECK (role IN ('admin', 'pengurus')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE jamaah (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(120) NOT NULL,
    kategori VARCHAR(20) NOT NULL
        CHECK (kategori IN ('Umum', 'Generus', 'Ibu-ibu')),
    alamat VARCHAR(500),
    no_telepon VARCHAR(30),
    aktif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_jamaah_nama ON jamaah (nama);
CREATE INDEX idx_jamaah_kategori ON jamaah (kategori);
CREATE INDEX idx_jamaah_aktif ON jamaah (aktif);

CREATE FUNCTION update_updated_at_column() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_jamaah_updated_at
    BEFORE UPDATE ON jamaah
    FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TABLE presensi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jamaah_id BIGINT NOT NULL REFERENCES jamaah (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    tanggal DATE NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('Hadir', 'Izin', 'Alpa')),
    jenis_pengajian VARCHAR(40) NOT NULL
        CHECK (jenis_pengajian IN ('Pengajian Umum', 'Pengajian Generus', 'Pengajian Ibu-ibu')),
    dicatat_oleh BIGINT REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_presensi_jamaah_acara UNIQUE (jamaah_id, tanggal, jenis_pengajian)
);
CREATE INDEX idx_presensi_tanggal_jenis ON presensi (tanggal, jenis_pengajian);

CREATE TABLE kegiatan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(160) NOT NULL UNIQUE,
    deskripsi VARCHAR(500),
    aktif BOOLEAN NOT NULL DEFAULT TRUE,
    dibuat_oleh BIGINT REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_kegiatan_aktif ON kegiatan (aktif);

CREATE TABLE ceklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kegiatan_id BIGINT NOT NULL REFERENCES kegiatan (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    bulan DATE NOT NULL CHECK (EXTRACT(DAY FROM bulan) = 1),
    status VARCHAR(20) NOT NULL DEFAULT 'Belum Selesai'
        CHECK (status IN ('Belum Selesai', 'Selesai')),
    diperbarui_oleh BIGINT REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ceklist_kegiatan_bulan UNIQUE (kegiatan_id, bulan)
);
CREATE INDEX idx_ceklist_bulan ON ceklist (bulan);

CREATE TRIGGER trg_ceklist_updated_at
    BEFORE UPDATE ON ceklist
    FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
