CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Pastikan tabel users sesuai kebutuhan portal (drop jika ada tabel users bawaan/lama yang tidak memiliki kolom password_hash)
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'users'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'password_hash'
    ) THEN
        DROP TABLE public.users CASCADE;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nama VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'pengurus'
        CHECK (role IN ('admin', 'pengurus')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS jamaah (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(120) NOT NULL,
    kategori VARCHAR(20) NOT NULL
        CHECK (kategori IN ('Umum', 'Generus', 'Ibu-ibu')),
    alamat VARCHAR(500),
    no_telepon VARCHAR(30),
    aktif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_jamaah_nama ON jamaah (nama);
CREATE INDEX IF NOT EXISTS idx_jamaah_kategori ON jamaah (kategori);
CREATE INDEX IF NOT EXISTS idx_jamaah_aktif ON jamaah (aktif);

CREATE OR REPLACE FUNCTION update_updated_at_column() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_jamaah_updated_at ON jamaah;
CREATE TRIGGER trg_jamaah_updated_at BEFORE UPDATE ON jamaah FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TABLE IF NOT EXISTS presensi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jamaah_id BIGINT NOT NULL REFERENCES jamaah (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    tanggal DATE NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('Hadir', 'Izin', 'Alpa')),
    jenis_pengajian VARCHAR(40) NOT NULL
        CHECK (jenis_pengajian IN ('Pengajian Umum', 'Pengajian Generus', 'Pengajian Ibu-ibu')),
    dicatat_oleh BIGINT REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_presensi_jamaah_acara UNIQUE (jamaah_id, tanggal, jenis_pengajian)
);
CREATE INDEX IF NOT EXISTS idx_presensi_tanggal_jenis ON presensi (tanggal, jenis_pengajian);

CREATE TABLE IF NOT EXISTS kegiatan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(160) NOT NULL UNIQUE,
    deskripsi VARCHAR(500),
    aktif BOOLEAN NOT NULL DEFAULT TRUE,
    dibuat_oleh BIGINT REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_kegiatan_aktif ON kegiatan (aktif);

CREATE TABLE IF NOT EXISTS ceklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kegiatan_id BIGINT NOT NULL REFERENCES kegiatan (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    bulan DATE NOT NULL CHECK (EXTRACT(DAY FROM bulan) = 1),
    status VARCHAR(20) NOT NULL DEFAULT 'Belum Selesai'
        CHECK (status IN ('Belum Selesai', 'Selesai')),
    diperbarui_oleh BIGINT REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ceklist_kegiatan_bulan UNIQUE (kegiatan_id, bulan)
);
CREATE INDEX IF NOT EXISTS idx_ceklist_bulan ON ceklist (bulan);

DROP TRIGGER IF EXISTS trg_ceklist_updated_at ON ceklist;
CREATE TRIGGER trg_ceklist_updated_at BEFORE UPDATE ON ceklist FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TABLE IF NOT EXISTS app_sessions (
    session_id VARCHAR(128) PRIMARY KEY,
    session_data TEXT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_app_sessions_expires_at ON app_sessions (expires_at);

